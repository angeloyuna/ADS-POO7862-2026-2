package ads.poo;

public class Endereco {
    
    private String rua;
    private String numero;
    private String bairro;
    private String cidade;
    private String uf;
    private String pais;
    private String cep;
    
    public Endereco(String rua, String numero, String bairro, String cidade, String uf, String pais, String cep) {
        this.rua = rua;
        this.numero = numero;
        this.bairro = bairro;
        this.cidade = cidade;
        this.uf = uf;
        this.pais = pais;
        this.cep = cep;
    } 
}
